#!/usr/bin/env python3
"""The two sample logs behind "Try with a sample" (the try page's machine-log tab and /agents).

    TET_CLI=path/to/tet-cli python3 scripts/make_machine_log_samples.py

Writes app/lib/machine_log_samples.mjs. Every file in it is written by the real
tools/machine-notebook/notebook.py and signed by the real `tet-cli agent sign`, under a throwaway
test device key made for this run; each sample carries what the real `notebook.py verify` printed.
scripts/try_machine_log_guard.mjs holds the page's verdict on each sample to that output.

  consistent  a greenhouse sensor's log: three readings; record 2 uses a one-time permission
              ("open-vent", open until record 3) once.            -> VALID
  reused      the same log, but record 3 uses that permission again. Record 3 is written and signed
              exactly as notebook.py writes one (its `record` refuses this before writing), so the
              signature is valid and only the one-time rule can refuse it.   -> INVALID

device.key is never written to the module: the device phrase is thrown away with the temp folder.
"""

import importlib.util
import json
import os
import shutil
import sys
import tempfile

sys.dont_write_bytecode = True

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "app", "lib", "machine_log_samples.mjs")

# The fixture generator's helpers: notebook.py main() in-process, snapshot without device.key, verify.
spec = importlib.util.spec_from_file_location("make_machine_log_fixture", os.path.join(HERE, "make_machine_log_fixture.py"))
fx = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fx)


def main():
    if not os.path.exists(fx.CLI):
        sys.exit(f"tet-cli not found at {fx.CLI}; set TET_CLI")
    samples = []
    with tempfile.TemporaryDirectory() as t:
        good = os.path.join(t, "greenhouse-sensor")
        keyid = fx.init(good)
        pid = fx.permit(good, "open-vent", 3)
        fx.record(good, 18.5, "C")
        fx.record(good, 27.0, "C", permit=pid)
        fx.record(good, 22.5, "C")

        twice = os.path.join(t, "greenhouse-sensor-2")
        shutil.copytree(good, twice)
        for ext in (".json", ".json.sig.json"):
            os.remove(os.path.join(twice, "records", "3" + ext))
        with open(os.path.join(twice, "chain.txt")) as f:
            lines = f.read().splitlines()[:2]
        with open(os.path.join(twice, "chain.txt"), "w") as f:
            f.write("".join(x + "\n" for x in lines))
        fx.forced_record(twice, 28.0, "C", pid)

        for sid, d in (("consistent", good), ("reused", twice)):
            files = fx.snapshot(d)
            assert "device.key" not in files
            samples.append({"id": sid, "folder": os.path.basename(d), "files": files, "verify": fx.verify(d)})

    body = json.dumps({"keyid": keyid, "permit": pid, "samples": samples}, indent=1, ensure_ascii=False)
    with open(OUT, "w") as f:
        f.write(
            "// GENERATED by scripts/make_machine_log_samples.py (real notebook.py and tet-cli, a throwaway\n"
            "// test key). Do not edit by hand; re-run the script. Files are base64; device.key is not here.\n"
            f"export const MACHINE_LOG_SAMPLES = {body};\n"
        )
    for s in samples:
        print(f"{s['id']:12} exit {s['verify']['exit']}: {s['verify']['stdout'].splitlines()[0]}")


if __name__ == "__main__":
    main()
